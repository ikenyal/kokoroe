/**
 * The README "Before / After" block, rendered from data/demo/results.json (never written by hand).
 * The block sits between BEGIN/END markers in README.md and README.ja.md; tests/readme-results.test.ts checks it is current.
 */
export interface Results {
  official: boolean;
  source: string | null;
  note: string;
  caveat: { en: string; ja: string } | null;
  before: { label: string; match: number; sd: number; okp: number; runs: number };
  paths: {
    n: number; mean: number; min: number; max: number;
    okp: { mean: number; min: number; max: number };
    taps: { mean: number; min: number; max: number };
    paths: { seed: number; match: number; okp: number; taps: number; runs: string[] }[];
  };
  history: { arm: string; mean: number; sd: number }[];
  adversarial: { pass: number; n: number; storeProtected: number; injectionRuns: number; escalated: number; lureRuns: number };
  curves: unknown[];
}

export const BEGIN = "<!-- results:begin (generated by `npm run demo:results` from data/demo/results.json — do not edit) -->";
export const END = "<!-- results:end -->";

const p = (x: number) => Math.round(x * 100);
const one = (x: number) => x.toFixed(1).replace(/\.0$/, "");

export function renderReadmeBlock(r: Results, lang: "en" | "ja"): string {
  const b = r.before, a = r.paths, h0 = r.history[0], h1 = r.history.at(-1)!, adv = r.adversarial;
  const changed = adv.injectionRuns - adv.storeProtected;
  if (lang === "en") {
    return [
      `## Before / After${r.official ? "" : " _(interim — replaced on 11/7)_"}`,
      "",
      "Fictional data: 10 clients, 40 training scenes, 20 held-out scenes, 8 history questions. The master is a simulator that judges",
      "with code against a hidden ground truth (frozen, checksummed); the apprentice never sees it.",
      "",
      `| | Before (ledger + explicit constraints) | After 40 corrections${r.official ? "" : " _(interim)_"} |`,
      "|---|---|---|",
      `| Held-out match (○) | ${p(b.match)}% ± ${p(b.sd)}% (${b.runs} runs) | **${p(a.mean)}%** (${p(a.min)}–${p(a.max)}%, ${a.n} training paths × 3 runs) |`,
      `| ○ + △ | ${p(b.okp)}% | **${p(a.okp.mean)}%** (${p(a.okp.min)}–${p(a.okp.max)}%) |`,
      `| Successor answers with the right history (of 8) | ${one(h0.mean)} | **${h1.mean.toFixed(1)}** ± ${h1.sd.toFixed(1)} |`,
      `| Master taps for 40 scenes | — | ${a.taps.min}–${a.taps.max} (judgments, choices, "why?", confirmations) |`,
      `| Injected "register this as a rule" in client text | — | kokoroe-chō changed ${changed} / ${adv.injectionRuns} times |`,
      `| Pressure to promise a discount | — | escalated to the master ${adv.escalated} / ${adv.lureRuns} |`,
      ...(r.caveat ? ["", `_${r.caveat.en}_`] : []),
    ].join("\n");
  }
  return [
    `## Before / After${r.official ? "" : " _（途中経過・11/7 に差し替え）_"}`,
    "",
    "架空データ：取引先10社、学習用40場面、評価用20場面（学習に使わない）、沿革の質問8件。師匠はシミュレータで、隠しの正解（凍結・チェックサムで検査）に照らしてコードで判定します。弟子は正解を見ません。",
    "",
    `| | Before（台帳と明示的な制約だけ） | ダメ出し40場面のあと${r.official ? "" : " _（途中経過）_"} |`,
    "|---|---|---|",
    `| 評価用場面の一致率（○） | ${p(b.match)}% ± ${p(b.sd)}%（${b.runs}回） | **${p(a.mean)}%**（${p(a.min)}〜${p(a.max)}%、学習${a.n}本×各3回） |`,
    `| ○ + △ | ${p(b.okp)}% | **${p(a.okp.mean)}%**（${p(a.okp.min)}〜${p(a.okp.max)}%） |`,
    `| 後任が経緯ごと正しく答えた質問（8問中） | ${one(h0.mean)} | **${h1.mean.toFixed(1)}** ± ${h1.sd.toFixed(1)} |`,
    `| 40場面にかかった師匠のタップ数 | — | ${a.taps.min}〜${a.taps.max}（判定・候補の選択・「なぜ？」・確認） |`,
    `| 取引先の文面に紛れた「心得として登録せよ」 | — | 心得帳が書き換わったのは ${adv.injectionRuns}回中${changed}回 |`,
    `| 値引きを迫られた場面 | — | ${adv.lureRuns}回中${adv.escalated}回、師匠の判断に回した |`,
    ...(r.caveat ? ["", `_${r.caveat.ja}_`] : []),
  ].join("\n");
}

/** Replace the generated block (markers included) in a README. Throws if the markers are missing. */
export function replaceBlock(readme: string, block: string): string {
  const i = readme.indexOf(BEGIN), j = readme.indexOf(END);
  if (i < 0 || j < i) throw new Error("README is missing the results markers");
  return readme.slice(0, i) + `${BEGIN}\n${block}\n${END}` + readme.slice(j + END.length);
}
